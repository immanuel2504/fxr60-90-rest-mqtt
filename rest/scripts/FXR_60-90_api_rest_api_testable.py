#!/usr/bin/env python3
"""
FXR_60-90_api_rest_api_testable.py
==================================
Build ``rest/FXR_60-90_rest_api_testable.yaml`` for Swagger UI **Try it out**
with a reader IP / hostname field. Does not change the standard Swagger output.

Requires the standard build first:

    python rest/scripts/FXR_60-90_api_rest_api.py
    python rest/scripts/FXR_60-90_api_rest_api_testable.py

Open:

    rest/docs/swagger-test.html
"""
from __future__ import annotations

import copy
import importlib.util
import sys
from collections import OrderedDict
from pathlib import Path

PACKAGE_DIR = Path(__file__).resolve().parent.parent
SCRIPTS_DIR = Path(__file__).resolve().parent
ROOT = PACKAGE_DIR.parent
if str(SCRIPTS_DIR) not in sys.path:
    sys.path.insert(0, str(SCRIPTS_DIR))

from build_fxr90_rest_api import load_yaml  # type: ignore  # noqa: E402

_rest_spec = importlib.util.spec_from_file_location(
    "fxr_rest_build",
    SCRIPTS_DIR / "FXR_60-90_api_rest_api.py",
)
fxr_rest = importlib.util.module_from_spec(_rest_spec)
assert _rest_spec.loader is not None
_rest_spec.loader.exec_module(fxr_rest)

SOURCE_YAML = PACKAGE_DIR / "FXR_60-90_rest_api.yaml"
TESTABLE_OUT = PACKAGE_DIR / "FXR_60-90_rest_api_testable.yaml"

AUTO_HEADER = (
    "# AUTO-GENERATED by rest/scripts/FXR_60-90_api_rest_api_testable.py — do not edit.\n"
    "# Swagger UI testable REST API (reader IP in Servers section).\n"
    "# Source: FXR_60-90_rest_api.yaml + servers overlay.\n"
    "# Rebuild: python rest/scripts/FXR_60-90_api_rest_api_testable.py\n"
)

TESTING_INFO_APPEND = (
    "\n"
    "# Testing\n"
    "\n"
    "In the **Servers** section above, enter the reader IP address or hostname in the "
    "`readerHost` field, choose HTTPS or HTTP, then use **Try it out** on an operation.\n"
)

READER_SERVERS = [
    OrderedDict(
        [
            ("url", "https://{readerHost}"),
            (
                "description",
                "FXR reader (HTTPS) — enter the reader IP or hostname in readerHost.",
            ),
            (
                "variables",
                OrderedDict(
                    [
                        (
                            "readerHost",
                            OrderedDict(
                                [
                                    ("default", "YOUR_READER_IP"),
                                    (
                                        "description",
                                        "Reader IP address or hostname (e.g. 192.168.1.50)",
                                    ),
                                ]
                            ),
                        ),
                    ]
                ),
            ),
        ]
    ),
    OrderedDict(
        [
            ("url", "http://{readerHost}"),
            (
                "description",
                "FXR reader (HTTP) — use when HTTPS is not enabled on the reader.",
            ),
            (
                "variables",
                OrderedDict(
                    [
                        (
                            "readerHost",
                            OrderedDict(
                                [
                                    ("default", "YOUR_READER_IP"),
                                    (
                                        "description",
                                        "Reader IP address or hostname (e.g. 192.168.1.50)",
                                    ),
                                ]
                            ),
                        ),
                    ]
                ),
            ),
        ]
    ),
]


def dump_yaml(path: Path, data: dict) -> None:
    import yaml

    with path.open("w", encoding="utf-8") as fh:
        fh.write(AUTO_HEADER)
        yaml.safe_dump(
            data,
            fh,
            sort_keys=False,
            allow_unicode=True,
            default_flow_style=False,
        )


def main() -> int:
    if not SOURCE_YAML.is_file():
        print(f"Missing {SOURCE_YAML.name}. Run FXR_60-90_api_rest_api.py first.", file=sys.stderr)
        return 1

    import build_fxr90_rest_api  # noqa: F401

    spec = load_yaml(SOURCE_YAML)
    out = copy.deepcopy(spec)

    info = out.get("info")
    if not isinstance(info, dict):
        info = OrderedDict()
        out["info"] = info
    else:
        info = OrderedDict(info)
        out["info"] = info

    description = str(info.get("description") or "").rstrip()
    if "# Testing" not in description:
        info["description"] = description + TESTING_INFO_APPEND

    out["servers"] = copy.deepcopy(READER_SERVERS)

    dump_yaml(TESTABLE_OUT, out)

    print(f"Source          : {SOURCE_YAML.relative_to(ROOT)}")
    print(f"Output (test)   : {TESTABLE_OUT.relative_to(ROOT)}")
    print("Swagger UI      : rest/docs/swagger-test.html")

    try:
        from openapi_spec_validator import validate as _validate  # type: ignore

        _validate(load_yaml(TESTABLE_OUT))
        print("openapi-spec-validator: VALID")
    except ImportError:
        print("openapi-spec-validator: not installed (skipped)")
    except Exception as exc:  # noqa: BLE001
        print(f"openapi-spec-validator: ISSUES -> {exc}")
        return 1

    return 0


if __name__ == "__main__":
    sys.exit(main())
