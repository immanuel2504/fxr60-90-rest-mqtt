"""
FXR_60-90_api_rest_api.py
=========================
Build the **final** ``FXR60-90/rest/FXR_60-90_rest_api.yaml`` for Swagger UI by combining:

 * **Schemas + operation metadata** from ``RestDeveloperfile.yaml`` (this package)
 * **Rich operation descriptions** from ``operation_descriptions/*.md``
 * **Request/response examples** from ``operation_examples/<path>/<METHOD>/*.json``

Run:

    python FXR60-90/rest/scripts/FXR_60-90_api_rest_api.py

Do not edit ``FXR_60-90_rest_api.yaml`` by hand — it is generated.
"""
